(function () {
  var d = document, dict = window.I18N, lang = 'en';

  function detect() {
    var l = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return /^es/i.test(l) ? 'es' : 'en';
  }
  /* t("key", {name: "x"}, "fallback"): current language, then English, then the fallback/key. */
  function t(key, vars, fallback) {
    var v = dict[lang] && dict[lang][key];
    if (v == null) v = dict.en[key];
    if (v == null) v = fallback != null ? fallback : key;
    if (vars) v = v.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
    return v;
  }

  function apply() {
    d.documentElement.lang = lang;
    Array.prototype.forEach.call(d.querySelectorAll('[data-i18n]'), function (el) {
      var v = dict[lang][el.getAttribute('data-i18n')];
      if (v != null) el.innerHTML = v;
    });
    Array.prototype.forEach.call(d.querySelectorAll('[data-i18n-attr]'), function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':'), v = p.length === 2 && dict[lang][p[1]];
        if (v != null && v !== false) el.setAttribute(p[0], v);
      });
    });
    d.title = t('meta_title');
    var md = d.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('meta_description'));
    Array.prototype.forEach.call(d.querySelectorAll('[data-lang]'), function (b) {
      b.setAttribute('aria-pressed', b.getAttribute('data-lang') === lang);
    });
    d.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
  }
  function set(l) { if ((l === 'en' || l === 'es') && l !== lang) { lang = l; apply(); } }

  d.addEventListener('click', function (e) {
    var b = e.target.closest && e.target.closest('[data-lang]');
    if (b) set(b.getAttribute('data-lang'));
  });

  window.t = t;
  window.I18N_API = { t: t, set: set, get: function () { return lang; } };
  var first = detect();
  if (first === 'es') { lang = 'es'; apply(); }   /* English is already in the HTML */
})();
